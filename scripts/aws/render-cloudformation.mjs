/**
 * Builds aws/cloudformation.yml from aws/cloudformation.template.yml by
 * embedding aws/cloudfront/url-rewrite.js and aws/content-security-policy.txt,
 * so each lives in one place (and the function and CSP are unit/e2e tested).
 *
 *   npm run aws:template        (writes)
 *   npm run aws:template -- --check   (fails if the committed file is stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const template = read('aws/cloudformation.template.yml');
const fn = read('aws/cloudfront/url-rewrite.js').trim();
const csp = read('aws/content-security-policy.txt').trim();

const indent = '          ';
const out =
  '# GENERATED by scripts/aws/render-cloudformation.mjs from aws/cloudformation.template.yml.\n' +
  '# Do not edit by hand: change the template, url-rewrite.js or content-security-policy.txt and re-run.\n' +
  template
    .replace(`${indent}__URL_REWRITE__`, fn.split('\n').map((l) => (l ? indent + l : '')).join('\n'))
    .replace('__CSP__', JSON.stringify(csp));

if (out.includes('__URL_REWRITE__') || out.includes('__CSP__')) throw new Error('placeholder not replaced');

const target = join(root, 'aws/cloudformation.yml');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== out) {
    console.error('aws/cloudformation.yml is out of date. Run: npm run aws:template');
    process.exit(1);
  }
  console.log('aws/cloudformation.yml is up to date');
} else {
  writeFileSync(target, out);
  console.log('wrote aws/cloudformation.yml');
}
